-- 1. Sequences
CREATE SEQUENCE CHAT_MSG_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_CHAT_ROOM START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

-- 2. Table CHAT_ROOM (Salons de discussion 1-to-1)
CREATE TABLE CHAT_ROOM (
    ID NUMBER PRIMARY KEY,
    ROOM_ID VARCHAR2(100) NOT NULL UNIQUE,
    USER1_ID VARCHAR2(100) NOT NULL,
    USER2_ID VARCHAR2(100) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    LAST_MESSAGE_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_CHAT_ROOM_USERS ON CHAT_ROOM (USER1_ID, USER2_ID);
CREATE INDEX IDX_CHAT_ROOM_LAST_MSG ON CHAT_ROOM (LAST_MESSAGE_AT DESC);

-- 3. Table CHAT_MESSAGE (Messages echanges)
CREATE TABLE CHAT_MESSAGE (
    ID NUMBER PRIMARY KEY,
    SENDER_ID VARCHAR2(100) NOT NULL,
    SENDER_NAME NVARCHAR2(255),
    RECEIVER_ID VARCHAR2(100),
    ROOM_ID VARCHAR2(100),
    CONTENT CLOB,
    MESSAGE_TYPE VARCHAR2(30),
    TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    IS_READ NUMBER(1) DEFAULT 0
);

CREATE INDEX IDX_CHAT_MSG_ROOM ON CHAT_MESSAGE (ROOM_ID);
CREATE INDEX IDX_CHAT_MSG_SENDER ON CHAT_MESSAGE (SENDER_ID);
CREATE INDEX IDX_CHAT_MSG_RECEIVER ON CHAT_MESSAGE (RECEIVER_ID);
CREATE INDEX IDX_CHAT_MSG_TIME ON CHAT_MESSAGE (TIMESTAMP);

-- 4. Table USER_STATUS (Presence en temps reel)
CREATE TABLE USER_STATUS (
    USER_ID VARCHAR2(100) PRIMARY KEY,
    IS_ONLINE NUMBER(1) DEFAULT 0,
    LAST_SEEN TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
